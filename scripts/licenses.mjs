#!/usr/bin/env node
// Production dependency licenses: writes THIRD-PARTY-NOTICES.md, or with --check fails when a
// shipped package has a license outside ALLOWED or the committed notices miss/extra a package.
//
//   node scripts/licenses.mjs           regenerate THIRD-PARTY-NOTICES.md
//   node scripts/licenses.mjs --check   CI gate (never writes)
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const NOTICES = `${root}THIRD-PARTY-NOTICES.md`;

/** SPDX ids we accept in shipped code. OFL-1.1 covers the self-hosted fonts, CC-BY-4.0 content. */
export const ALLOWED = [
  'MIT',
  'ISC',
  '0BSD',
  'BSD-2-Clause',
  'BSD-3-Clause',
  'Apache-2.0',
  'OFL-1.1',
  'CC-BY-4.0',
];

/**
 * Bundled into the app but declared as devDependencies, so `pnpm licenses list --prod` misses
 * them: vite-plugin-pwa injects its service-worker register module into the client bundle.
 */
const BUNDLED_DEV = [{ name: 'vite-plugin-pwa', from: 'apps/web' }];

/** @param {Record<string, {name: string, versions: string[], license: string}[]>} json */
export function flatten(json) {
  const rows = [];
  for (const [group, pkgs] of Object.entries(json)) {
    for (const p of pkgs) {
      for (const version of p.versions)
        rows.push({ name: p.name, version, license: p.license ?? group });
    }
  }
  return rows.sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
}

function allowed(expr) {
  const e = (expr ?? '').trim().replace(/^\((.*)\)$/, '$1');
  if (!e) return false;
  if (/\s+OR\s+/.test(e)) return e.split(/\s+OR\s+/).some(allowed);
  if (/\s+AND\s+/.test(e)) return e.split(/\s+AND\s+/).every(allowed);
  return ALLOWED.includes(e);
}

/** Rows whose license is not allowed (including missing or Unknown). */
export function checkEntries(rows) {
  return rows.filter((r) => !allowed(r.license));
}

export function render(rows) {
  const lines = [
    '# Third-party notices',
    '',
    'Packages shipped in the Prep Desk app (production dependencies, including the engine',
    "packages' runtime dependencies, plus build-time code bundled into the app). Generated by",
    '`node scripts/licenses.mjs`; do not edit by hand. Each package is under the license named',
    'here; its full text is in the package. Prep Desk content is CC-BY-4.0 (see each content pack).',
    '',
    '| Package | Version | License |',
    '| --- | --- | --- |',
    ...rows.map((r) => `| ${r.name} | ${r.version} | ${r.license} |`),
    '',
  ];
  return lines.join('\n');
}

function parseNotices(md) {
  const map = new Map();
  for (const m of md.matchAll(/^\| (\S+) \| (\S+) \| [^|]+ \|$/gm)) {
    if (m[1] !== 'Package' && m[1] !== '---') map.set(m[1], m[2]);
  }
  return map;
}

/** Packages missing from / extra in the committed notices, and ones whose version moved. */
export function compareNotices(rows, md) {
  const committed = parseNotices(md);
  const current = new Map(rows.map((r) => [r.name, r.version]));
  const missing = [...current.keys()].filter((n) => !committed.has(n));
  const extra = [...committed.keys()].filter((n) => !current.has(n));
  const drifted = [...current].filter(([n, v]) => committed.has(n) && committed.get(n) !== v);
  return { missing, extra, drifted: drifted.map(([n]) => n) };
}

function collect() {
  const out = execFileSync('pnpm', ['licenses', 'list', '--prod', '--json'], {
    cwd: root,
    encoding: 'utf8',
    stdio: ['ignore', 'pipe', 'inherit'],
  });
  const rows = flatten(JSON.parse(out));
  for (const { name, from } of BUNDLED_DEV) {
    const pkg = JSON.parse(
      readFileSync(`${root}${from}/node_modules/${name}/package.json`, 'utf8'),
    );
    rows.push({ name, version: pkg.version, license: pkg.license });
  }
  return rows.sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
}

function main(argv) {
  const rows = collect();
  const bad = checkEntries(rows);
  for (const r of bad)
    console.error(`license not allowed: ${r.name}@${r.version} (${r.license || 'none'})`);
  if (!argv.includes('--check')) {
    writeFileSync(NOTICES, render(rows));
    console.log(`wrote THIRD-PARTY-NOTICES.md (${rows.length} packages)`);
    return bad.length ? 1 : 0;
  }
  let committed = '';
  try {
    committed = readFileSync(NOTICES, 'utf8');
  } catch {
    console.error('THIRD-PARTY-NOTICES.md is missing; run `node scripts/licenses.mjs`.');
    return 1;
  }
  const { missing, extra, drifted } = compareNotices(rows, committed);
  if (missing.length) console.error(`not in THIRD-PARTY-NOTICES.md: ${missing.join(', ')}`);
  if (extra.length) console.error(`no longer shipped but listed: ${extra.join(', ')}`);
  if (drifted.length)
    console.warn(`version changed (regenerate when convenient): ${drifted.join(', ')}`);
  const failed = bad.length > 0 || missing.length > 0 || extra.length > 0;
  if (failed)
    console.error('Fix the license or run `node scripts/licenses.mjs` and commit the result.');
  else console.log(`licenses ok (${rows.length} production packages)`);
  return failed ? 1 : 0;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  process.exitCode = main(process.argv.slice(2));
}
